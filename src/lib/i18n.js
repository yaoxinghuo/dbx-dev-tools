function detect() {
  return locale().toLowerCase().startsWith("zh") ? "zh" : "en";
}
let currentLang = detect();
const subscribers = new Set();

// Re-detect on both init (real locale arrives) and env pushes (locale changes).
function update() {
  const next = detect();
  if (next !== currentLang) {
    currentLang = next;
    for (const fn of subscribers) fn(currentLang);
  }
}
onEnvChange(update);
onInit(update);

export function lang() {
  return currentLang;
}

export function onLangChange(fn) {
  subscribers.add(fn);
  return () => subscribers.delete(fn);
}

export function t() {
  return messages[currentLang];
}

// Search must match a tool regardless of which language the query is in, so
// Home builds its index from every locale, not just the active one.
export function allMessages() {
  return messages;
}
